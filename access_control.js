(function (AC) {
  var STORAGE_KEY = "study_admin_verified_password";

  // このブラウザが管理者として認証済み（＝全教科・全ページバイパス可）かどうか
  AC.isAdminBypass = function () {
    try {
      return window.localStorage.getItem(STORAGE_KEY) === AC.adminPassword;
    } catch (e) {
      return false;
    }
  };

  // パスワード認証成功時に呼ぶ。以後このブラウザは全教科バイパスになる
  AC.setAdminBypass = function () {
    try {
      window.localStorage.setItem(STORAGE_KEY, AC.adminPassword);
    } catch (e) {}
  };

  // 指定した教科（フォルダ名）・指定したページ（省略可）が閲覧可能か。
  //   isAllowed("英語一列")             → 教科レベルの許可のみ判定
  //   isAllowed("英語一列", "session9") → 教科レベル＋ページレベルの両方を判定
  // ページIDが pages[教科] に載っていない場合は「教科が許可されていれば許可」。
  AC.isAllowed = function (subjectName, pageId) {
    if (AC.isAdminBypass()) return true;
    if (!AC.all) return false;
    if (!AC.subjects[subjectName]) return false;

    if (pageId) {
      var subjectPages = AC.pages[subjectName];
      if (subjectPages && Object.prototype.hasOwnProperty.call(subjectPages, pageId)) {
        return !!subjectPages[pageId];
      }
    }
    return true;
  };
})(window.ACCESS_CONTROL);
