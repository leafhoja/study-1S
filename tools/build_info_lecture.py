def extract_slides(slug):
 """PDFをページ単位で抽出する。画像だけのページもページ番号を保持する。"""
 pdf = SLIDES / f"{slug}.pdf"
 # PDFから文字を取り出すコマンドを実行し、その結果をページごとに分ける。
 result = subprocess.run(["pdftotext", "-layout", str(pdf), "-"], check=True,
                         stdout=subprocess.PIPE, stderr=subprocess.PIPE)
 pages = result.stdout.decode("utf-8", errors="replace").split("\f")
 # 空行や対象外の行を除き、各ページで使う文字を集める。
 cleaned = []
 for page in pages:
  lines = []
  for raw in page.splitlines():
   line = re.sub(r"\s+", " ", raw).strip()
   if not line or line in {"AB", "A", "B", "発展", "再配布不可", "質問タイム"}:
    continue
   if "いらすとや" in line or line.startswith("<") and line.endswith(">"):
    continue
   lines.append(line)
  if lines:
   cleaned.append(lines)
 return cleaned

